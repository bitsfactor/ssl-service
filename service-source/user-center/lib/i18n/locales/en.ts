// Recursively widen string literal types to plain `string` so other
// locales can satisfy the structural shape with their own translations.
type Widen<T> = T extends string
  ? string
  : T extends Record<string, unknown>
    ? { [K in keyof T]: Widen<T[K]> }
    : T;

export type Messages = Widen<typeof en>;
